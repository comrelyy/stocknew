@with_retry
def stock_individual_fund_flow_rank(indicator: str = "5日") -> pd.DataFrame:
    df = ak.stock_individual_fund_flow_rank(indicator=indicator)
    if df is None or df.empty:
        return df
    return reorder(df, _INDIV_COLS[indicator])


